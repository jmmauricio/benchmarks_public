"""## Construcción del modelo"""

grid = BpsBuilder('k13p2.hjson', use_casadi=True)
grid.construct('k13p2')
bld = CasadiBuilder(grid.sys_dict).build()

"""## Uso del modelo

### Estado estacionario y análisis de pequeña señal
"""

model = CasadiModel(bld)
model.ini({},'xy_0.json')
eig(model)
mode_idx, lambda_i = get_mode(model, f_min = 1, f_max = 1.5)
omega_n = lambda_i.imag

# residue_i = residue(model, 'v_ref_LT', 'omega_LT', mode_idx=mode_idx)[0][0]
# np.angle(residue_i, deg=True)

params = {}
opt_params = {'damp_crit_max':1.0}
for phase_rad_per_leadlag in np.linspace(np.deg2rad(10), np.deg2rad(80), 1000):

    alpha = (1 + np.sin(phase_rad_per_leadlag))/(1 - np.sin(phase_rad_per_leadlag))
    T_2 = 1/(omega_n*np.sqrt(alpha))
    T_1 = alpha*T_2
    T_3 = T_1
    T_4 = T_2
    T_w = 10.0
    K_stab = 0.1

    params.update({'K_stab_pss_LT':K_stab,
                  'T_w_pss_LT':T_w,
                'T_1_pss_LT':  T_1,
                'T_2_pss_LT':  T_2,
                'T_3_pss_LT':  T_3,
                'T_4_pss_LT':  T_4})

    model.ini(params,'xy_0.json')
    eig(model)
    mode_idx, lambda_i = get_mode(model, f_min = 0.5, f_max = 1.5, report=False)
    omega_n = lambda_i.imag
    damping = -lambda_i.real/np.abs(lambda_i)
    print(damping)
    if damping < opt_params['damp_crit_max']:
        opt_params.update({'damp_crit_max':damping,
                           'phase_rad_per_leadlag':phase_rad_per_leadlag,
                           'T_1':T_1,
                           'T_2':T_2,
                           'T_3':T_3,
                           'T_4':T_4})
        
print(f"Optimal phase per lead-lag = {np.rad2deg(opt_params['phase_rad_per_leadlag']):0.2f}º")

    
