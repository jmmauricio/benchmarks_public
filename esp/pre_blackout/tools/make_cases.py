"""Produce the three cases as standalone, self-contained hjson files.

    python tools/make_cases.py

Each output must reproduce its documented modes from the file alone -- no runtime
arguments, no environment variables, nothing held in a caller's head.  That is the
whole point of this script: case 1 previously depended on a generation trim passed
on the command line, so the file on disk described a different operating point from
the one its numbers came from.
"""
import os
import re
import subprocess
import sys

import hjson

HERE = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.dirname(HERE)
os.chdir(BASE)

PY = sys.executable
DEV = 'esp_preblackout_dev.hjson'
TUNED = 'esp_preblackout_pss_tuned.hjson'
BENCH = 'esp_preblackout_pod_bench.hjson'

CASE1 = 'esp_case1_preblackout.hjson'
CASE2 = 'esp_case2_pod_bench.hjson'
CASE3 = 'esp_case3_normal.hjson'

TRIM_MW = 625.0          # brings the ES-FR export to the observed ~1,450 MW


def header(lines):
    return ''.join(f'// {ln}\n' if ln else '//\n' for ln in lines)


def set_field(txt, anchor, key, value, fmt='{}'):
    a = txt.index(f'"name": "{anchor}"')
    m = re.compile(rf'("{key}":\s*)(-?[\d.eE+]+)').search(txt, a)
    if m is None:
        raise ValueError(f'{key} not found for {anchor}')
    return txt[:m.start(2)] + fmt.format(value) + txt[m.end(2):]


# ─────────────────────────────────────────────────────────────────────────────
# Case 1 — pre-blackout, 28 April 2025 around 12:20
# ─────────────────────────────────────────────────────────────────────────────
env = dict(os.environ, CHAIN_SRC=os.path.join(BASE, DEV),
           CHAIN_OUT=os.path.join(BASE, CASE1))
subprocess.run([PY, os.path.join(HERE, 'make_chain.py'), '22', '22'],
               check=True, env=env, capture_output=True)

text = open(CASE1, encoding='utf-8').read()
data = hjson.loads(text)
EXT = {'SLACK_FR', 'CE_CENTRE', 'CE_EAST'}
sched = {s['name']: s.get('lc', {}).get('p_c_lc_mw', 0.0)
         for s in data['syns'] if s['name'] not in EXT}
total = sum(sched.values())
scale = (total - TRIM_MW)/total

# Bake the trim in.  Previously this was a command-line argument, so the file
# described a 2,025 MW export while the published modes came from 1,451 MW.
for name, p in sched.items():
    if p:
        text = set_field(text, name, 'p_c_lc_mw', p*scale, '{:.4f}')

text = header([
    'CASE 1 - Spanish system, 28 April 2025, around 12:20',
    '',
    'Reproduces the East-Centre-West inter-area oscillation at 0.2 Hz observed',
    'between 12:19 and 12:22.  Continental Europe is represented as a three-group',
    'chain (West / Centre / East) so that a CE-wide mode exists at all; the base',
    'case represents everything past the border as one stiff machine and cannot',
    'produce a mode slower than about 0.33 Hz.',
    '',
    'Expected:  0.202 Hz at zeta = 3.53 %  (East-Centre-West; Iberia and West in',
    '           antiphase with East, Centre near a node)',
    '           0.301 Hz at zeta = 1.54 %',
    '           0.384 Hz at zeta = -2.94 %   <-- UNSTABLE',
    '',
    'WARNING: this case contains an unstable mode.  It is correct for studying the',
    '0.2 Hz oscillation and unsuitable as a stable base point.  The stabilisers are',
    'left at their as-found settings (most at zero gain), which is what produces it.',
    '',
    'ES-FR export 1,451 MW, matching the 1,300-1,450 MW read off RE SCADA figures',
    '2-22 and 2-23 for 12:15-12:22.  The 866 MW and 190 MW figures quoted in the',
    'report text are the countertrading response, after the event.',
    '',
    'The CE group inertias and corridor reactances are plausible, not sourced: they',
    'are chosen so the West-end mode lands at 0.2 Hz.  Say so if you publish this.',
    '',
    'Generated by tools/make_cases.py.  See CASES.md.',
]) + text
open(CASE1, 'w', encoding='utf-8').write(text)
print(f'wrote {CASE1}  (trim of {TRIM_MW:.0f} MW baked in)')


# ─────────────────────────────────────────────────────────────────────────────
# Case 2 — stressed N-1 at the 5% criterion, the POD bench
# ─────────────────────────────────────────────────────────────────────────────
text = header([
    'CASE 2 - POD test bench: stressed N-1 at the 5 % criterion',
    '',
    'Stable, nothing unstable anywhere, with a lightly damped inter-area mode for',
    'developing power oscillation damping controllers on PV plant.',
    '',
    'Expected:  0.262 Hz at zeta = 5.14 %   <-- the target mode',
    '           worst mode in the system 1.113 Hz at zeta = 4.24 %',
    '',
    'Three ingredients, none of them a statement about any operator practice:',
    '  1. synchronous plant committed at 52 % of base by stored energy',
    '     (55,512 MW.s, 46 % of the 119,474 MW.s reported at 12:30), PV taking up',
    '     the released 4,072 MW; 15.9 % synchronous share of generation',
    '  2. N-1 outage of one of the two ES-FR circuits, exchange reduced to 988 MW',
    '     as the remaining circuit (P_max 2,647 MW) requires',
    '  3. stabilisers tuned by the residue method to the NTS-SEPE 5 % criterion,',
    '     not beyond it',
    '',
    'Sensitivity: with the stabilisers removed this same case is unstable at',
    '-16.22 %.  The margin is NOT obtained by weakening stabilisers.',
    '',
    'Note: synchronous machines CAN damp this mode - tuning to a 10 % target',
    'reaches about 14 %.  The supportable claim is that tuned to the criterion',
    'rather than beyond it, the system sits at the criterion.',
    '',
    'Generated by tools/make_cases.py.  See CASES.md and README_pod_bench.md.',
]) + open(BENCH, encoding='utf-8').read()
open(CASE2, 'w', encoding='utf-8').write(text)
print(f'wrote {CASE2}')


# ─────────────────────────────────────────────────────────────────────────────
# Case 3 — well-damped normal operation
# ─────────────────────────────────────────────────────────────────────────────
text = header([
    'CASE 3 - well-damped normal operation',
    '',
    'The healthy reference case.  Base network, base dispatch, interconnection',
    'intact; the only change from esp_preblackout_dev.hjson is that the',
    'stabilisers are tuned by the residue method against a 10 % target, which is',
    'beyond the 5 % criterion.',
    '',
    'Expected:  worst electromechanical mode 1.242 Hz at zeta = 6.33 %',
    '           inter-area mode 0.327 Hz at zeta = 9.28 %',
    '           every mode stable',
    '',
    'Three stabilisers are committed - CCGT_ES620, hydro_ES113_hydro,',
    'hydro_ES432_hydro - and the other 52 are commented out rather than left at',
    'zero gain, so the model carries no inert stabiliser states (820 states rather',
    'than 976).',
    '',
    'It stops at 6.33 % rather than the 10 % requested because the excitation',
    'systems run out of phase: at the 1.0-1.24 Hz modes machine after machine needs',
    '145-178 degrees of lead, i.e. 73-89 per stage against a 70 limit.  At 1.74 Hz',
    'every machine here, including the 3.8 GVA CCGT, has arg(GEP) about -167.',
    'Three lead-lag stages or faster excitation is the lever, not more tuning.',
    '',
    'Generated by tools/make_cases.py.  See CASES.md.',
]) + open(TUNED, encoding='utf-8').read()
open(CASE3, 'w', encoding='utf-8').write(text)
print(f'wrote {CASE3}')
